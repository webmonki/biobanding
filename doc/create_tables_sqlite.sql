	ID INTEGER,
	FK_PLAYER INTEGER,
	ENRY_TEXT TEXT,
	HEIGHT INTEGER,
	SITTING_HEIGHT INTEGER,
	WEIGHT INTEGER,
	BODY_SPAN INTEGER,
