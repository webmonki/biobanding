	ID INTEGER,
	FIRST_NAME TEXT,
	LAST_NAME TEXT
);

CREATE TABLE PLAYER_DETAIL (
	ID INTEGER,
	FK_PLAYER INTEGER,
	TEXT_OF_BIRTH TEXT,
	SEX_M_0_F_1 INTEGER,
	HEIGHT_FATHER INTEGER,
	HEIGHT_MOTHER INTEGER
);

